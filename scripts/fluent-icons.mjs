// State glyphs: a pinned pin, a timer's play and stop, the active tab, a closed day.
const FILLED = ['pin', 'play', 'stop', 'calendar', 'client', 'contacts', 'settings', 'done'];
const SIZES = [16, 20, 24];

const root = new URL('..', import.meta.url);
const pkg = new URL('node_modules/@fluentui/svg-icons/', root);
const version = JSON.parse(readFileSync(new URL('package.json', pkg))).version;

function paths(file, size, style) {
    const svg = readFileSync(new URL(`icons/${file}_${size}_${style}.svg`, pkg), 'utf8').trim();
    const box = `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">`;
    const inner = svg.startsWith(box) && svg.endsWith('</svg>') ? svg.slice(box.length, -'</svg>'.length) : null;
    const ds = inner === null ? [] : [...inner.matchAll(/<path d="([^"]+)"\/>/g)].map(([, d]) => d);
    if (ds.length === 0 || inner.replace(/<path d="[^"]+"\/>/g, '') !== '') {
        throw new Error(`${file}_${size}_${style} is not plain paths in a ${size} px box`);
    }
    // A space before a fraction that follows another fraction draws the same path, and chained fractions no longer read as an IPv4 address to the public export's gate.
    return ds.map((d) => d.replace(/(\.\d+)(?=\.\d)/g, '$1 '));
}

const variant = (file, style) => Object.fromEntries(SIZES.map((size) => [size, paths(file, size, style)]));

const entries = Object.entries(GLYPHS).map(([name, file]) => {
    const glyph = { regular: variant(file, 'regular'), ...(FILLED.includes(name) ? { filled: variant(file, 'filled') } : {}) };
    return `    '${name}': ${JSON.stringify(glyph)},`;
});

writeFileSync(
    new URL('resources/js/components/ui/icon/fluent.ts', root),
    `// Generated by scripts/fluent-icons.mjs from @fluentui/svg-icons ${version}; do not edit by hand.
// Fluent UI System Icons, MIT License, Copyright (c) 2020 Microsoft Corporation.
type Sized = Record<16 | 20 | 24, string[]>;

export const FLUENT = {
${entries.join('\n')}
} satisfies Record<string, { regular: Sized; filled?: Sized }>;
`,
);
console.log(`fluent.ts: ${entries.length} icons`);
